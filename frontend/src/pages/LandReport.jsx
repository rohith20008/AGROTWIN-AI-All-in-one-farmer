import { jsPDF } from "jspdf";
import { motion } from "framer-motion";

export default function LandReport() {

  const generateReport = () => {
    const doc = new jsPDF();

    const margin = 20;
    let y = 20;

    // HEADER BAR
    doc.setFillColor(20, 80, 40);
    doc.rect(0, 0, 210, 25, "F");

    doc.setTextColor(255, 255, 255);
    doc.setFontSize(16);
    doc.text("AGRICULTURE DEPARTMENT", margin, 12);

    doc.setFontSize(11);
    doc.text("AI LAND HEALTH REPORT", margin, 20);

    doc.setTextColor(0, 0, 0);

    y = 40;

    // SECTION FUNCTION
    const section = (title) => {
      doc.setFontSize(13);
      doc.text(title, margin, y);
      doc.setDrawColor(0);
      doc.line(margin, y + 2, 190, y + 2);
      y += 10;
    };

    // ROW FUNCTION
    const row = (label, value) => {
      doc.setFontSize(11);
      doc.text(label, margin, y);
      doc.text(value, 120, y);
      y += 8;
    };

    // FARM INFO
    section("Farm Information");
    row("Farm ID", "AGRO-1023");
    row("Date", new Date().toLocaleDateString());

    // SOIL HEALTH
    y += 5;
    section("Soil Health Analysis");

    doc.setTextColor(255, 0, 0);
    row("Nitrogen", "0 (Critical Low)");
    row("Phosphorus", "0 (Critical Low)");
    row("Potassium", "0 (Critical Low)");

    doc.setTextColor(0, 0, 0);
    row("pH", "0 (Unbalanced)");

    // ENVIRONMENT
    y += 5;
    section("Environmental Conditions");
    row("Temperature", "28°C");
    row("Moisture", "Low");

    // CROP
    y += 5;
    section("Recommended Crop");
    doc.setTextColor(0, 120, 0);
    row("Crop", "Banana (High Profit)");
    doc.setTextColor(0, 0, 0);

    // FERTILIZER
    y += 5;
    section("Fertilizer Plan");
    row("Urea", "75 kg/acre");
    row("Potash", "30 kg/acre");

    // RISK
    y += 5;
    section("Risk Assessment");

    doc.setTextColor(255, 0, 0);
    row("Nutrient Risk", "HIGH");

    doc.setTextColor(255, 165, 0);
    row("Water Risk", "MEDIUM");

    doc.setTextColor(0, 0, 0);

    // AI SUGGESTIONS
    y += 5;
    section("AI Recommendations");

    doc.setFontSize(10);
    doc.text("• Apply nitrogen-based fertilizers immediately", margin, y);
    y += 7;
    doc.text("• Maintain irrigation within 24 hours", margin, y);
    y += 7;
    doc.text("• Avoid high water-demand crops", margin, y);

    // FOOTER
    doc.setFontSize(9);
    doc.setTextColor(100);
    doc.text(
      "Generated by Agro AI Intelligence System",
      margin,
      285
    );

    doc.save("Land_Report.pdf");
  };

  return (
    <div style={styles.container}>

      <motion.h1
        initial={{ opacity: 0 }}
        animate={{ opacity: 1 }}
        style={styles.title}
      >
        🌾 AI LAND REPORT GENERATOR
      </motion.h1>

      <motion.div
        whileHover={{ scale: 1.05 }}
        style={styles.card}
      >
        <h3 style={styles.sub}>SYSTEM STATUS</h3>

        <p>Soil Condition: <span style={styles.bad}>CRITICAL</span></p>
        <p>Temperature: 28°C</p>
        <p>NPK Levels: 0 / 0 / 0</p>

        <button onClick={generateReport} style={styles.button}>
          GENERATE OFFICIAL REPORT
        </button>
      </motion.div>
            {/* TERMINAL PANEL */}
      <motion.div
        initial={{ opacity: 0 }}
        animate={{ opacity: 1 }}
        style={styles.terminal}
      >
        <h3 style={styles.sub}>AI ANALYSIS FEED</h3>
        <div style={styles.logBox}>
          <p>[00] Soil Scan Complete</p>
          <p>[01] Nutrient Deficiency Detected</p>
          <p>[02] Crop Optimization Model Loaded</p>
          <p>[03] Fertilizer Strategy Generated</p>
          <p>[04] Report Ready for Download</p>
        </div>
      </motion.div>

      {/* BACKGROUND GRID */}
      <div style={styles.gridOverlay}></div>

    </div>
  );
}

